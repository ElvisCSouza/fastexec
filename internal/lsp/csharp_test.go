// csharpFixture writes the solution every exactness assertion below runs
// against. One solution, one project, one client: the requests are cheap once
// loaded, and starting csharp-ls costs more than all of them together.
func csharpFixture(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	writeFixture(t, root, "demo.sln", csSolution)
	writeFixture(t, root, "NuGet.config", csNuGetConfig)

	app := filepath.Join(root, "src", "App")
	writeFixture(t, app, "App.csproj", csProject)
	writeFixture(t, app, "Conta.cs", csConta)
	writeFixture(t, app, "Cliente.cs", csCliente)
	writeFixture(t, app, "Uso.cs", csUso)
	writeFixture(t, app, "Gerado.g.cs", csGerado)
	writeFixture(t, app, "Repositorio.cs", csRepositorio)
	writeFixture(t, app, "Repo.cs", csRepo)
	writeFixture(t, app, "RepoUso.cs", csRepoUso)
	writeFixture(t, app, "Split.Part1.cs", csSplitPart1)
	writeFixture(t, app, "Split.Part2.cs", csSplitPart2)
	writeFixture(t, app, "Extensoes.cs", csExtensoes)
	writeFixture(t, app, "ExtUso.cs", csExtUso)
	writeFixture(t, app, "Record.cs", csRecord)
	writeFixture(t, app, "RecordUso.cs", csRecordUso)
	writeFixture(t, app, "Tipos.cs", csTipos)
	writeFixture(t, app, "Bagunca.cs", csBagunca)
	return root
}

// restoreFixture restores the fixture, or skips the test.
//
// The test runs restore because FastExec never does: the product refuses to
// launch a server on a project whose packages were not restored and tells the
// user the command to run. Making the fixture restorable is therefore the
// test's job, and it is done here, offline, with a NuGet config that has no
// source at all.
func restoreFixture(t *testing.T, root string) {
	t.Helper()
	sdk, portable := dotnetSDK()
	if sdk == "" {
		t.Skip("no .NET SDK on this machine: csharp-ls could load nothing, so there is nothing to measure")
	}
	env := append(os.Environ(),
		"DOTNET_ROOT="+sdk,
		"DOTNET_CLI_TELEMETRY_OPTOUT=1",
		"DOTNET_NOLOGO=1",
		// Keep the packages folder inside the fixture: the test must not write to
		// the user's profile any more than it must download from the network.
		"NUGET_PACKAGES="+filepath.Join(root, "packages"),
	)
	if portable {
		env = append(env, "PATH="+sdk+string(os.PathListSeparator)+os.Getenv("PATH"))
	}
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Minute)
	defer cancel()

	cmd := exec.CommandContext(ctx, dotnetExe(sdk), "restore", filepath.Join(root, "demo.sln"))
	cmd.Dir = root
	cmd.Env = env
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("dotnet restore of the fixture failed (%v); the output ends with:\n%s", err, tailLines(string(out), 15))
	}
}

// realCsharp starts the csharp-ls this machine has, through the same discovery
// the daemon uses, or skips.
func realCsharp(t *testing.T, root string) *Client {
	t.Helper()
	if Disabled() {
		t.Skip("FASTEXEC_LSP is off")
	}
	lang := csharpLanguage(t)
	launch, ok := LaunchFor(lang, root)
	if !ok {
		t.Skipf("%s not installed: %s", lang.Primary().Name, lang.Primary().Install)
	}
	if launch.Problem != "" {
		t.Skipf("this machine cannot run %s: %s", lang.Primary().Name, launch.Problem)
	}
	c, err := New(context.Background(), Config{
		Launch:           launch,
		HandshakeTimeout: 60 * time.Second,
		Timeout:          120 * time.Second,
	})
	if err != nil {
		t.Fatalf("starting the real %s: %v", lang.Primary().Name, err)
	}
	t.Cleanup(c.Close)
	return c
}

// TestCSharpRealServerIsExact drives one loaded solution through every operation
// the C# entry promises, and checks each answer against the gabarito.
func TestCSharpRealServerIsExact(t *testing.T) {
	root := csharpFixture(t)
	restoreFixture(t, root)
	c := realCsharp(t, root)
	ctx := context.Background()

	// The gate, against the real server. csharp-ls announces the load as
	// blocking progress; while it is in flight no answer may be trusted, so a
	// query with a small budget has to come back as a load rather than as an
	// empty list.
	// csharp-ls 0.28 loads the solution lazily: nothing is announced after the
	// handshake, and the load starts with the first document request (measured:
	// no $/progress for 69 s without one; begin, report and end arrive within
	// about two seconds of the request). The first request is therefore what
	// starts the load, and it runs in the background while the gate watches.
	// Not awaited: waiting for the answer would wait for the load to end and
	// turn the gate check below into the fast-machine branch.
	go func() {
		_, _ = c.DocumentSymbols(ctx, filepath.Join(root, "src", "App", "Conta.cs"))
	}()
	title := waitBusy(t, c, 60*time.Second)
	t.Logf("the server announced %q", title)
	if !strings.Contains(strings.ToLower(title), "loading") {
		t.Errorf("the announced title is %q, want the blocking 'loading' progress the table declares", title)
	}
	if err := c.WaitLoaded(ctx, 250*time.Millisecond); err != nil {
		var le *LoadingError
		if !errors.As(err, &le) {
			t.Fatalf("a query during the load = %v, want a LoadingError", err)
		}
		if !errors.Is(err, ErrLoading) {
			t.Error("a loading answer must still satisfy errors.Is(err, ErrLoading)")
		}
		if got := Degraded(err); got != "lsp loading C# solution…; by name" {
			t.Errorf("Degraded(during the load) = %q, want the note the tools layer shows", got)
		}
	} else {
		// The fixture is one small project: on a fast machine the load can end
		// inside the grace. That is also a correct answer, and the load gate's
		// wording is pinned deterministically by the fake-server test.
		t.Log("the fixture loaded within a 250ms budget; nothing to degrade")
	}

	loaded := time.Now()
	if err := c.WaitLoaded(ctx, 5*time.Minute); err != nil {
		t.Fatalf("WaitLoaded after the load ended: %v", err)
	}
	t.Logf("the solution was ready %v after the query above", time.Since(loaded))
	if title, busy := c.Loading(); busy {
		t.Fatalf("Loading() = %q after the load ended, want not busy", title)
	}

	// Every assertion from here on is about a loaded project. A filter of the
	// generated file is applied by the bridge, not by the server, so the server's
	// own answer is what is asserted below.
	app := filepath.Join(root, "src", "App")

	t.Run("overloads", func(t *testing.T) {
		need(t, "references", c.Capabilities().References)
		path, pos := posInFile(t, root, filepath.Join("src", "App", "Conta.cs"), "Salvar(int id) { }", "Salvar")

		// Salvar(int): the int call, the generated one, and nothing else — not
		// the string call, not the two-argument call, not the same-named method
		// on Cliente.
		wantRefs(t, "References(Conta.Salvar(int))",
			refsAt(t, c, root, path, pos),
			"src/App/Gerado.g.cs:6", "src/App/Uso.cs:7")

		// With the declaration included, the answer gains this overload's own
		// line: the flag is the difference between "where is this used" and
		// "where is this defined and used".
		wantRefs(t, "References(Conta.Salvar(int), declarations included)",
			refsAtDecl(t, c, root, path, pos, true),
			"src/App/Conta.cs:5", "src/App/Gerado.g.cs:6", "src/App/Uso.cs:7")

		path, pos = posInFile(t, root, filepath.Join("src", "App", "Conta.cs"), "Salvar(string nome)", "Salvar")
		wantRefs(t, "References(Conta.Salvar(string))",
			refsAt(t, c, root, path, pos),
			"src/App/Uso.cs:8")

		path, pos = posInFile(t, root, filepath.Join("src", "App", "Conta.cs"), "Salvar(int id, string nome)", "Salvar")
		wantRefs(t, "References(Conta.Salvar(int, string))",
			refsAt(t, c, root, path, pos),
			"src/App/Uso.cs:9")
	})

	t.Run("same name on another type", func(t *testing.T) {
		need(t, "references", c.Capabilities().References)
		path, pos := posInFile(t, root, filepath.Join("src", "App", "Cliente.cs"), "Salvar(int id)", "Salvar")
		wantRefs(t, "References(Cliente.Salvar)",
			refsAt(t, c, root, path, pos),
			"src/App/Uso.cs:10")
	})

	t.Run("definition", func(t *testing.T) {
		need(t, "definition", c.Capabilities().Definition)
		path, pos := posInFile(t, root, filepath.Join("src", "App", "Uso.cs"), "conta.Salvar(1);", "Salvar")
		// The call with an int argument must land on the int overload, not on the
		// first Salvar in the file.
		wantRefs(t, "Definition(conta.Salvar(1))",
			locsOf(t, "Definition", root, func() ([]Location, error) { return c.Definition(ctx, path, pos) }),
			"src/App/Conta.cs:5")
	})

	t.Run("interface to implementation", func(t *testing.T) {
		need(t, "implementation", c.Capabilities().Implementation)
		path, pos := posInFile(t, root, filepath.Join("src", "App", "Repositorio.cs"), "void Gravar(int id)", "Gravar")
		wantRefs(t, "Implementation(IRepositorio.Gravar)",
			locsOf(t, "Implementation", root, func() ([]Location, error) { return c.Implementation(ctx, path, pos) }),
			"src/App/Repo.cs:5")
		wantRefs(t, "References(IRepositorio.Gravar)",
			refsAt(t, c, root, path, pos),
			"src/App/RepoUso.cs:7")
	})

	t.Run("partial class", func(t *testing.T) {
		need(t, "references", c.Capabilities().References)
		path, pos := posInFile(t, root, filepath.Join("src", "App", "Split.Part2.cs"), "Somar(int a, int b)", "Somar")
		// The call sits in the other half of the partial class.
		wantRefs(t, "References(Split.Somar)",
			refsAt(t, c, root, path, pos),
			"src/App/Split.Part1.cs:5")
	})

	t.Run("extension method", func(t *testing.T) {
		need(t, "definition", c.Capabilities().Definition)
		path, pos := posInFile(t, root, filepath.Join("src", "App", "ExtUso.cs"), "21.Dobrar()", "Dobrar")
		// Called on a literal: the receiver is not a name, so a name search has
		// nothing to follow.
		wantRefs(t, "Definition(21.Dobrar())",
			locsOf(t, "Definition", root, func() ([]Location, error) { return c.Definition(ctx, path, pos) }),
			"src/App/Extensoes.cs:5")
	})

	t.Run("nameof", func(t *testing.T) {
		need(t, "references", c.Capabilities().References)
		path, pos := posInFile(t, root, filepath.Join("src", "App", "Record.cs"), "public string Nome", "Nome")
		wantRefs(t, "References(Pedido.Nome)",
			refsAt(t, c, root, path, pos),
			"src/App/RecordUso.cs:5")
	})

	t.Run("document symbols", func(t *testing.T) {
		need(t, "documentSymbol", c.Capabilities().DocumentSymbol)
		syms, err := c.DocumentSymbols(ctx, filepath.Join(app, "Conta.cs"))
		if err != nil {
			t.Fatalf("DocumentSymbols: %v", err)
		}
		names := make([]string, 0, len(syms))
		overloads := 0
		for _, s := range syms {
			names = append(names, s.Name)
			// csharp-ls names a method symbol with its parameter list, so the
			// overloads are told apart by the signature rather than by kind
			// alone: "Salvar(int id)", "Salvar(string nome)", "Salvar(int id,
			// string nome)". FastExec passes that through as the server sent it.
			if strings.HasPrefix(s.Name, "Salvar(") {
				overloads++
			}
		}
		if !contains(names, "Conta") {
			t.Errorf("DocumentSymbols(Conta.cs) = %v, want the class", names)
		}
		// Three overloads, three symbols: a server that deduplicates by name
		// would break every "go to symbol" flow for C#.
		if overloads != 3 {
			t.Errorf("DocumentSymbols(Conta.cs) has %d Salvar symbols, want 3 (%v)", overloads, names)
		}
	})

	t.Run("hover", func(t *testing.T) {
		need(t, "hover", c.Capabilities().Hover)
		path, pos := posInFile(t, root, filepath.Join("src", "App", "Uso.cs"), "conta.Salvar(1);", "Salvar")
		h, err := c.HoverAt(ctx, path, pos)
		if err != nil {
			t.Fatalf("HoverAt: %v", err)
		}
		if h == nil {
			t.Fatal("HoverAt returned nothing for a method call")
		}
		if !strings.Contains(h.Contents, "Salvar") || !strings.Contains(h.Contents, "int") {
			t.Errorf("HoverAt(conta.Salvar(1)) = %q, want the int overload", h.Contents)
		}
		if strings.Contains(h.Contents, "string") {
			t.Errorf("HoverAt(conta.Salvar(1)) = %q, want a type, not the whole overload group", h.Contents)
		}

		path, pos = posInFile(t, root, filepath.Join("src", "App", "Uso.cs"), `conta.Salvar("nome");`, "Salvar")
		h, err = c.HoverAt(ctx, path, pos)
		if err != nil {
			t.Fatalf("HoverAt(string): %v", err)
		}
		if h == nil || !strings.Contains(h.Contents, "string") {
			t.Errorf("HoverAt(conta.Salvar(\"nome\")) = %v, want the string overload", h)
		}
	})

	t.Run("rename", func(t *testing.T) {
		need(t, "rename", c.Capabilities().Rename)
		path, pos := posInFile(t, root, filepath.Join("src", "App", "Conta.cs"), "Salvar(int id) { }", "Salvar")

		if rng, placeholder, err := c.PrepareRename(ctx, path, pos); err != nil {
			t.Errorf("PrepareRename: %v", err)
		} else if rng == nil || rng.End.Character-rng.Start.Character != len("Salvar") {
			t.Errorf("PrepareRename range = %v (placeholder %q), want the word Salvar", rng, placeholder)
		}

		we, err := c.Rename(ctx, path, pos, "Gravar")
		if err != nil {
			t.Fatalf("Rename: %v", err)
		}
		edited := editedFiles(t, root, we)

		// Renaming one overload touches its declaration and its one call, plus the
		// generated call the server cannot know is generated. If the other
		// overloads move too, the user's code stops compiling — which is exactly
		// what the server's own answer does (TestCSharpServerRenameIsNotPerSymbol),
		// so Rename built these edits from the reference list instead.
		if got := edited["src/App/Conta.cs"]; len(got) != 1 || got[0].Range.Start.Line != 4 {
			t.Errorf("Rename edited Conta.cs as %v, want only the int overload on line 5", got)
		}
		uso := edited["src/App/Uso.cs"]
		if len(uso) != 1 || uso[0].Range.Start.Line != 6 {
			t.Errorf("Rename edited Uso.cs as %v, want only the int call on line 7", uso)
		}
		for _, kv := range edited {
			for _, e := range kv {
				if e.NewText != "Gravar" {
					t.Errorf("a rename edit replaces with %q, want Gravar", e.NewText)
				}
			}
		}
		for file := range edited {
			switch file {
			case "src/App/Conta.cs", "src/App/Uso.cs", "src/App/Gerado.g.cs":
			default:
				t.Errorf("Rename touched %s, which has no use of this overload", file)
			}
		}
		if _, ok := edited["src/App/Cliente.cs"]; ok {
			t.Error("Rename renamed Cliente.Salvar, a different type's method")
		}
	})

	t.Run("diagnostics and using quickfix", func(t *testing.T) {
		need(t, "diagnostics", c.Capabilities().Diagnostics)
		path := filepath.Join(app, "Tipos.cs")
		diags, err := c.Diagnostics(ctx, path, 30*time.Second)
		if err != nil {
			t.Fatalf("Diagnostics: %v", err)
		}
		var missing *Diagnostic
		for i := range diags {
			if strings.Contains(diags[i].Message, "StringBuilder") {
				missing = &diags[i]
				break
			}
		}
		if missing == nil {
			t.Fatalf("Diagnostics(Tipos.cs) = %v, want the missing-using error", diags)
		}
		if missing.Severity != 1 {
			t.Errorf("the missing-using diagnostic has severity %d, want an error", missing.Severity)
		}

		need(t, "codeAction", c.Capabilities().CodeAction)
		actions, err := c.CodeActions(ctx, path, missing.Range, []string{"quickfix"})
		if err != nil {
			t.Fatalf("CodeActions: %v", err)
		}
		// The fix the user wants here is "add using System.Text;". A code action
		// that does something else is fine to exist; one that adds the using has
		// to be among them, or the quickfix flow has nothing to offer.
		var offered []string
		for _, a := range actions {
			offered = append(offered, a.Title)
			if strings.Contains(a.Title, "System.Text") || editAddsUsing(a, "System.Text") {
				return
			}
		}
		t.Errorf("CodeActions(only quickfix) = %v, want one that adds using System.Text", offered)
	})

	t.Run("formatting", func(t *testing.T) {
		need(t, "formatting", c.Capabilities().Formatting)
		path := filepath.Join(app, "Bagunca.cs")
		edits, err := c.Formatting(ctx, path, FormattingOptions{TabSize: 4, InsertSpaces: true})
		if err != nil {
			t.Fatalf("Formatting: %v", err)
		}
		if len(edits) == 0 {
			t.Fatal("Formatting returned no edits for an unindented file")
		}
		changed := false
		for _, e := range edits {
			if e.NewText != textAt(t, path, e.Range) {
				changed = true
			}
		}
		if !changed {
			t.Error("Formatting returned only no-op edits for a file that is not indented")
		}
	})
}

// TestCSharpWithoutAnSDKDoesNotStartAServer is the degradation path, run for
// real: the machine reports no SDK, so the manager must refuse the launch and
