// wantRefs compares an exact answer against the gabarito. Equality, not
// containment: an answer that grew an extra use is as wrong as one that lost a
// use, and both are invisible to a name search.
func wantRefs(t *testing.T, what string, got []string, want ...string) {
	t.Helper()
	sort.Strings(want)
	same := len(got) == len(want)
	for i := range got {
		if !same || got[i] != want[i] {
			same = false
			break
		}
	}
	if !same {
		t.Errorf("%s =\n  %v\nwant\n  %v", what, got, want)
	}
}

// editAddsUsing reports whether a code action's edit inserts a using for pkg.
func editAddsUsing(a CodeAction, pkg string) bool {
	if a.Edit == nil {
		return false
	}
	for _, edits := range a.Edit.Changes {
		for _, e := range edits {
			if strings.Contains(e.NewText, pkg) {
				return true
			}
		}
	}
	for _, d := range a.Edit.DocumentChanges {
		for _, e := range d.Edits {
			if strings.Contains(e.NewText, pkg) {
				return true
			}
		}
	}
	return false
}

// textAt is the text a range covers, so a formatting test can tell a real edit
// from a no-op. The fixtures are pure ASCII, so a UTF-16 column is a byte offset.
func textAt(t *testing.T, path string, r Range) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s: %v", path, err)
	}
	lines := strings.Split(string(data), "\n")
	if int(r.End.Line) >= len(lines) {
		t.Fatalf("edit range %v is past the end of %s", r, filepath.Base(path))
	}
	if r.Start.Line == r.End.Line {
		return sliceAt(t, lines[r.Start.Line], int(r.Start.Character), int(r.End.Character))
	}
	parts := []string{sliceAt(t, lines[r.Start.Line], int(r.Start.Character), len(lines[r.Start.Line]))}
	parts = append(parts, lines[r.Start.Line+1:int(r.End.Line)]...)
	parts = append(parts, sliceAt(t, lines[r.End.Line], 0, int(r.End.Character)))
	return strings.Join(parts, "\n")
}

func sliceAt(t *testing.T, line string, from, to int) string {
	t.Helper()
	if from < 0 || to > len(line) || from > to {
		t.Fatalf("range %d:%d is outside %q", from, to, line)
	}
	return line[from:to]
}

// tailLines keeps the end of a command's output: the last lines are where a
// build or restore says what went wrong.
func tailLines(s string, n int) string {
	lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
	if len(lines) > n {
		lines = lines[len(lines)-n:]
	}
	return strings.Join(lines, "\n")
}
