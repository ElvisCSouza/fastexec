// apart). What makes C# "exact" is that Roslyn picks one symbol and reports its
// uses; so the assertions are exact lists, not "contains": a reference list that
// is missing a use, or that grew an extra one from the other overload, is the
// failure this whole layer exists to prevent.
//
// The test skips when the machine has no csharp-ls or no .NET SDK — it is a
// measurement of an install, not a unit test of the code.

