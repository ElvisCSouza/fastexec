// TestCSharpServerRenameIsNotPerSymbol pins the reason Launch.RenameByRefs
// exists, so the workaround is not removed as superstition.
//
// csharp-ls 0.16 answers textDocument/rename on one overload with edits for
// every overload that shares the name: here the int, the string and the two
// argument declarations all move. Applying that answer renames methods the
// caller never selected, which is why Rename builds its edits from the
// reference list instead. The raw request is what is asserted below; if a later
// csharp-ls renames only the selected symbol, this test fails and the flag can
// go.
func TestCSharpServerRenameIsNotPerSymbol(t *testing.T) {
	root := csharpFixture(t)
	restoreFixture(t, root)
	c := realCsharp(t, root)
	ctx := context.Background()
	_ = c.WaitLoaded(ctx, 5*time.Minute)

	path, pos := posInFile(t, root, filepath.Join("src", "App", "Conta.cs"), "Salvar(int id) { }", "Salvar")
	raw, err := c.Raw(ctx, "textDocument/rename", map[string]any{
		"textDocument": map[string]any{"uri": PathToURI(path)},
		"position":     pos,
		"newName":      "Gravar",
	})
	if err != nil {
		t.Fatalf("raw textDocument/rename: %v", err)
	}
	var we WorkspaceEdit
	if err := json.Unmarshal(raw, &we); err != nil {
		t.Fatalf("decoding the rename answer: %v", err)
	}
	decls := len(editedFiles(t, root, &we)["src/App/Conta.cs"])
	if decls < 2 {
		t.Skipf("this csharp-ls renames one overload only (%d edits): RenameByRefs can be dropped", decls)
	}
	t.Logf("csharp-ls renames %d declarations in Conta.cs for one selected overload: RenameByRefs stays", decls)
}

